    /// <summary>
    /// One base quantisation table scaled for the given quality, as the 65 bytes a DQT marker carries:
    /// the table-ID byte followed by 64 coefficients. Coefficients are clamped to 1–255, so quality 0
    /// and quality 7 both degenerate — to all-255 and all-1 respectively.
    /// </summary>
    public static byte[] LoadStandardDqt(ReadOnlySpan<byte> table, int quality)
    {
      var dst = new byte[65];
      dst[0] = table[0];

      int scale = DqtScales[Math.Clamp(quality, 0, 7)];
      for (int i = 0; i < 64; i++)
      {
        uint t = (uint)((table[i + 1] * scale + 50) / 100);
        dst[i + 1] = (byte)Math.Clamp(t, 1u, 255u);
      }
      return dst;
    }
